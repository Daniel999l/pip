// Test-only setup against a local node (default http://127.0.0.1:8545, see scripts/local/node.mjs).
// Deploys MockToken + Brain (from contracts/Brain.json), funds dev account #2 with tokens,
// and writes scripts/local/local.env (test-only env file, NOT .env).
// Usage: node scripts/local/setup.mjs [--no-wait] [--mongo-uri <uri>]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JsonRpcProvider, Wallet, ContractFactory, Contract, parseUnits } from 'ethers';
import { compileMock, MOCK_JSON } from './compileMock.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
// E2E_BRAIN_JSON lets the harness self-test against test/contracts/BrainStub.sol before the real Brain is built.
export const BRAIN_JSON = process.env.E2E_BRAIN_JSON ? path.resolve(process.env.E2E_BRAIN_JSON) : path.join(root, 'contracts', 'Brain.json');
export const LOCAL_ENV = path.join(here, 'local.env');
export const RPC_URL = 'http://127.0.0.1:8545';

// Well-known Hardhat/Anvil dev keys (publicly known, test only).
export const DEV_KEYS = [
  '0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80', // #0 deployer / owner
  '0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d', // #1 teacher
  '0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a', // #2 holder
  '0x7c852118294e51e653712a81e05800f419141751be58f605c371e15141b007a6', // #3 spare
];
export const DEAD = '0x000000000000000000000000000000000000dEaD';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export async function waitForBrainJson({ timeoutMs = 45 * 60_000, log = console.log } = {}) {
  const t0 = Date.now();
  let warned = false;
  while (Date.now() - t0 < timeoutMs) {
    try {
      const j = JSON.parse(fs.readFileSync(BRAIN_JSON, 'utf8'));
      if (Array.isArray(j.abi) && typeof j.bytecode === 'string' && j.bytecode.length > 10) return j;
    } catch {}
    if (!warned) { log(`[setup] waiting for ${BRAIN_JSON} ...`); warned = true; }
    await sleep(5000);
  }
  throw new Error('contracts/Brain.json did not appear in time');
}

export function readLocalEnv(file = LOCAL_ENV) {
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

export async function setup({ rpcUrl = RPC_URL, wait = true, mongoUri = null, log = console.log, seed = 42n } = {}) {
  const provider = new JsonRpcProvider(rpcUrl, undefined, { staticNetwork: true, cacheTimeout: -1, pollingInterval: 200 });
  const net = await provider.getNetwork();
  const [deployer, teacher, holder] = DEV_KEYS.map((k) => new Wallet(k, provider));

  const mock = fs.existsSync(MOCK_JSON) ? JSON.parse(fs.readFileSync(MOCK_JSON, 'utf8')) : compileMock();
  const brainJson = wait ? await waitForBrainJson({ log }) : JSON.parse(fs.readFileSync(BRAIN_JSON, 'utf8'));
  const brainBytecode = brainJson.bytecode.startsWith('0x') ? brainJson.bytecode : '0x' + brainJson.bytecode;

  let nonce = await provider.getTransactionCount(deployer.address, 'pending');
  const token = await new ContractFactory(mock.abi, mock.bytecode, deployer).deploy({ nonce: nonce++ });
  await token.waitForDeployment();
  const tokenAddress = await token.getAddress();
  log(`[setup] MockToken  ${tokenAddress}`);

  const brain = await new ContractFactory(brainJson.abi, brainBytecode, deployer).deploy(seed, teacher.address, { nonce: nonce++, gasLimit: 30_000_000 });
  const brainRc = await brain.deploymentTransaction().wait();
  const brainAddress = await brain.getAddress();
  log(`[setup] Brain      ${brainAddress} (deploy gas ${brainRc.gasUsed})`);

  const tx = await token.transfer(holder.address, parseUnits('10000000', 18), { nonce: nonce++ });
  await tx.wait();
  log(`[setup] gave 10,000,000 MOCK to holder ${holder.address}`);

  const env = {
    RPC_URL: rpcUrl,
    CHAIN_ID: String(net.chainId),
    TOKEN_ADDRESS: tokenAddress,
    BRAIN_ADDRESS: brainAddress,
    TEACHER_PRIVATE_KEY: DEV_KEYS[1],
    LESSON_EVERY_SEC: '3',
    BURN_PER_LESSON: '100000',
    EXPLORER: 'http://localhost',
  };
  if (mongoUri) env.MONGODB_URI = mongoUri;
  const body = '# Test-only env for the local e2e harness (dev keys are public). Generated by scripts/local/setup.mjs.\n' +
    Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n') + '\n';
  fs.writeFileSync(LOCAL_ENV, body);
  log(`[setup] wrote ${LOCAL_ENV}`);
  provider.destroy();
  return { env, tokenAddress, brainAddress, deployer: deployer.address, teacher: teacher.address, holder: holder.address, abi: brainJson.abi, tokenAbi: mock.abi };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const mi = args.indexOf('--mongo-uri');
  setup({ wait: !args.includes('--no-wait'), mongoUri: mi >= 0 ? args[mi + 1] : null })
    .then(() => process.exit(0))
    .catch((e) => { console.error(e); process.exit(1); });
}
